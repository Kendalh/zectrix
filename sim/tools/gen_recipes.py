#!/usr/bin/env python3
"""Generate firmware/main/common/recipes_data.inc from recipes/recipes.json + recipes/photos/<id>.jpg.

  gen_recipes.py --import-photos HOWTOCOOK_DIR   one-off: copy each recipe's "src" photo from a HowToCook
                                                 checkout (HOWTOCOOK/dishes/...) into recipes/photos/ as a
                                                 center-cropped 360x278 JPEG (2x the on-screen size)
  gen_recipes.py                                 write recipes_data.inc

Photos are center-cropped to 180x139, then Floyd-Steinberg dithered onto black/white/yellow/red and packed at
2 bpp, 4 pixels per byte, MSB first, 45 bytes per row. The codes are the rawdraw::Color values
(00 black, 01 white, 10 yellow, 11 red), the same as the AI painter's pictures. Run with `python3 -I`.
"""
import argparse
import json
import sys
from pathlib import Path

from PIL import Image, ImageEnhance

HERE = Path(__file__).resolve().parent
SRC = HERE / "recipes"
OUT = HERE.parent.parent / "firmware" / "main" / "common" / "recipes_data.inc"
PHOTO_W, PHOTO_H = 180, 139
PALETTE = [(0, 0, 0), (255, 255, 255), (255, 215, 0), (200, 0, 0)]  # index == 2 bpp code


def crop_to(img, w, h):
    """Center-crop to the aspect ratio of w:h, then resize."""
    ratio = w / h
    iw, ih = img.size
    if iw / ih > ratio:
        nw = round(ih * ratio)
        img = img.crop(((iw - nw) // 2, 0, (iw - nw) // 2 + nw, ih))
    else:
        nh = round(iw / ratio)
        img = img.crop((0, (ih - nh) // 2, iw, (ih - nh) // 2 + nh))
    return img.resize((w, h), Image.LANCZOS)


def import_photos(howtocook, recipes):
    (SRC / "photos").mkdir(exist_ok=True)
    for r in recipes:
        img = Image.open(Path(howtocook) / "dishes" / r["src"]).convert("RGB")
        crop_to(img, PHOTO_W * 2, PHOTO_H * 2).save(SRC / "photos" / f"{r['id']}.jpg", quality=88)
        print("imported", r["id"])


def pack_photo(path):
    img = crop_to(Image.open(path).convert("RGB"), PHOTO_W, PHOTO_H)
    img = ImageEnhance.Contrast(img).enhance(1.15)
    img = ImageEnhance.Color(img).enhance(1.3)
    pal = Image.new("P", (1, 1))
    pal.putpalette([c for rgb in PALETTE for c in rgb] + [0, 0, 0] * 252)
    q = img.quantize(palette=pal, dither=Image.FLOYDSTEINBERG)
    px = q.load()
    out = bytearray()
    for y in range(PHOTO_H):
        row = bytearray((PHOTO_W + 3) // 4)
        for x in range(PHOTO_W):
            row[x >> 2] |= (px[x, y] & 3) << (6 - (x & 3) * 2)
        out += row
    return bytes(out)


def c_str(s):
    return json.dumps(s, ensure_ascii=False)  # JSON string escapes are valid C for these inputs (no \u needed)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--import-photos", metavar="HOWTOCOOK_DIR")
    args = ap.parse_args()
    recipes = json.loads((SRC / "recipes.json").read_text(encoding="utf-8"))["recipes"]
    if args.import_photos:
        import_photos(args.import_photos, recipes)
        return

    lines = ["// Generated by sim/tools/gen_recipes.py from sim/tools/recipes/recipes.json. Do not edit.",
             "// Included by common/recipes.cc only.", ""]
    for i, r in enumerate(recipes):
        photo = pack_photo(SRC / "photos" / f"{r['id']}.jpg")
        lines.append(f"static const uint8_t kPhoto{i}[{len(photo)}] = {{")
        for k in range(0, len(photo), 24):
            lines.append("    " + ",".join(f"0x{b:02x}" for b in photo[k:k + 24]) + ",")
        lines.append("};")
        lines.append(f"static const RecipeItem kItems{i}[] = {{" +
                     ", ".join(f"{{{c_str(n)}, {c_str(a)}}}" for n, a in r["items"]) + "};")
        lines.append(f"static const char* const kSteps{i}[] = {{")
        lines += [f"    {c_str(s)}," for s in r["steps"]]
        lines.append("};")
        lines.append("")
    lines.append("const Recipe kRecipes[] = {")
    for i, r in enumerate(recipes):
        lines.append("    {" + ", ".join([
            c_str(r["id"]), c_str(r["title"]), c_str(r["tag"]), c_str(r["serving"]),
            str(r["stars"]), str(r["kcal"]), str(r.get("minutes", 0)), c_str(r["intro"]), c_str(r.get("tip", "")),
            f"kItems{i}", f"{len(r['items'])}", f"kSteps{i}", f"{len(r['steps'])}", f"kPhoto{i}"]) + "},")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(recipes)} recipes -> {OUT} ({OUT.stat().st_size} bytes of source)")


if __name__ == "__main__":
    sys.exit(main())
