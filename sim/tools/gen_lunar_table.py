#!/usr/bin/env python3
"""Generate firmware/main/common/lunar_table.inc (lunar year data, 2009-2050) with the lunar_python package.

    python3 -I sim/tools/gen_lunar_table.py PATH_TO_LUNAR_PYTHON_SRC > firmware/main/common/lunar_table.inc
    python3 -I sim/tools/gen_lunar_table.py PATH_TO_LUNAR_PYTHON_SRC --dump-days > /tmp/lunar_days.csv   # for checking

PATH_TO_LUNAR_PYTHON_SRC is the directory that contains the `lunar_python` package (pip download + extract it
somewhere outside the repo). Each table row describes one lunar year, from its Spring Festival:
    {month_bits, leap_month, spring_festival_month, spring_festival_day}
month_bits: bit i (0-based, in calendar order, a leap month follows its regular month) is set when that month has 30 days.
"""
import datetime
import sys

path = sys.argv[1]
sys.path.insert(0, path)
from lunar_python import Lunar, LunarYear, Solar  # noqa: E402

FIRST, LAST = 2009, 2050  # 2009 only for dates before the 2010 Spring Festival

if "--dump-days" in sys.argv:
    d = datetime.date(2010, 1, 1)
    while d <= datetime.date(2050, 12, 31):
        l = Solar.fromYmd(d.year, d.month, d.day).getLunar()
        m = l.getMonth()
        print(f"{d.isoformat()},{l.getYear()},{abs(m)},{l.getDay()},{1 if m < 0 else 0}")
        d += datetime.timedelta(days=1)
    sys.exit(0)

print("// Generated by sim/tools/gen_lunar_table.py (lunar_python). Do not edit by hand.")
print("// {month_bits, leap_month, spring_festival_month, spring_festival_day}, one row per lunar year.")
for year in range(FIRST, LAST + 1):
    months = LunarYear.fromYear(year).getMonths()
    start = next(i for i, m in enumerate(months) if m.getMonth() == 1)
    mine = []
    for m in months[start:]:
        if len(mine) >= 12 and m.getMonth() == 1:
            break
        mine.append(m)
    leap = next((abs(m.getMonth()) for m in mine if m.getMonth() < 0), 0)
    assert len(mine) == (13 if leap else 12), (year, len(mine))
    bits = sum(1 << i for i, m in enumerate(mine) if m.getDayCount() == 30)
    s = Lunar.fromYmd(year, 1, 1).getSolar()
    assert s.getYear() == year
    print(f"    {{0x{bits:04X}, {leap}, {s.getMonth()}, {s.getDay()}}},  // {year}")
